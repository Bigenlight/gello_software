    sid0 = mujoco.mj_name2id(m0, mujoco.mjtObj.mjOBJ_SITE, "pot/pot_opening")
    assert m0.site_type[sid0] == mujoco.mjtGeom.mjGEOM_SPHERE  # policy-observed model untouched
