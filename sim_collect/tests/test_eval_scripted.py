def test_scripted_policy_matches_harness_protocol(eval_world):
    from sim_collect.eval.policies import Policy
    pol = ScriptedPolicy(eval_world)
    assert isinstance(pol, Policy)
    assert pol.needs_images is False and pol.meta["policy"] == "scripted"
    assert np.allclose(pol.limits[0], eval_world.joint_limits_lo) and np.allclose(pol.limits[1], eval_world.joint_limits_hi)
    assert pol.reset(eval_world.info()) is None


def test_scripted_policy_success_rate_seeds_0_19(eval_world):
    results = []
    print()
    for seed in SEEDS:
        info, n, pol = _episode(eval_world, seed)
        outcome = info.get("outcome") or "timeout"
        results.append((seed, outcome, n))
        notes = "; ".join(l for l in pol.log if l.startswith(("slip", "FAIL")) or "timeout" in l)
        print(f"  seed {seed:2d}: {outcome:8s} steps={n:3d} t_success={info.get('t_success_s')} "
              f"clamped(limit/dev)={eval_world.n_clamped_limit}/{eval_world.n_clamped_dev} "
              f"| {info.get('detail')} {('| ' + notes) if notes else ''}")
        assert n <= 600
        # the oracle plans inside the world's own envelope, so the deploy clamps must stay idle
        assert eval_world.n_clamped_limit == 0, f"seed {seed}: envelope clamp fired {eval_world.n_clamped_limit}x"
    successes = [s for s, o, _ in results if o == "success"]
    failures = [(s, o) for s, o, _ in results if o != "success"]
    print(f"  SR {len(successes)}/{len(SEEDS)}  failures: {failures}")
    assert len(successes) >= 15, f"SR {len(successes)}/20 < 15; failures {failures}"
