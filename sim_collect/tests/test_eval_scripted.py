def _episode(world, seed: int, max_steps: int = 600):
    obs = world.reset(seed)
    policy = ScriptedPolicy(world)
    policy.reset(world.info())
    info = {"done": False, "outcome": None}
    n = 0
    for n in range(1, max_steps + 1):
        a = policy.act(obs)
        assert isinstance(a, list) and len(a) == 7 and all(math.isfinite(v) for v in a)
        assert 0.0 <= a[6] <= 1.0
        world.apply(a)
        info = world.step()
        obs = world.observe(images=False)
        if info["done"]:
            break
    return info, n, policy


