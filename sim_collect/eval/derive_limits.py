#!/usr/bin/env python
"""Derive the eval joint envelope (`eval.joint_limits_lo/hi`) from recorded takes.

    .venv/bin/python -m sim_collect.eval.derive_limits ros2_ur_ws/gello_logs/sim [--factor 1.2] [--json out.json]

Replicates the rule of the REAL deploy envelope (carrot_eef_limits.json, generated by
scripts/dataset/make_carrot_eef_limits.py — its note, verbatim: "1.2x expanded symmetric
about the centre of the OBSERVED state q only (... the recorded `command` stream is
excluded from the envelope) ... All intervals are quantised OUTWARD onto a 0.0001 grid
before the derived values are computed"):

    raw_min/raw_max = per-joint min/max of `ur_joint_states` q1..q6 over all takes,
                      quantised outward to 0.0001
    centre = (raw_min + raw_max) / 2,  half = (raw_max - raw_min) / 2 * factor
    lo/hi  = centre -/+ half, quantised outward to 0.0001

Check: the real file's joint_raw_min/max reproduce its joint_limits_lo/hi exactly with
this rule (J1: -3.7027/-2.6809 -> -3.8049/-2.5787). Prints a yaml block for the `eval:`
section (plus the sim start pose statistics for reference). The recorded `command`
stream is also scanned and reported (never used for the envelope, as in the real rule).
"""
from __future__ import annotations

import argparse
import datetime as _dt
import json
import math
import os
import subprocess
import sys
from typing import Any, Dict, List, Optional

import numpy as np

_ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
if _ROOT not in sys.path:
    sys.path.insert(0, _ROOT)

N_JOINTS = 6
GRID = 1e-4


def quantise_outward(lo: np.ndarray, hi: np.ndarray, grid: float = GRID) -> tuple:
    # values already on the grid (within 1e-7 grid units) stay put; everything else moves OUTWARD
    lo_q = np.floor(np.asarray(lo, dtype=float) / grid + 1e-7) * grid
    hi_q = np.ceil(np.asarray(hi, dtype=float) / grid - 1e-7) * grid
    return np.round(lo_q, 4), np.round(hi_q, 4)


def expand(raw_min: np.ndarray, raw_max: np.ndarray, factor: float = 1.2) -> tuple:
    """1.2x symmetric about the centre, both ends quantised outward (the real rule)."""
    rmin, rmax = quantise_outward(raw_min, raw_max)
    centre = (rmin + rmax) / 2.0
    half = (rmax - rmin) / 2.0 * float(factor)
    return quantise_outward(centre - half, centre + half)


def scan_takes(take_dirs: List[str]) -> Dict[str, Any]:
    import h5py
    qmin = np.full(N_JOINTS, np.inf); qmax = np.full(N_JOINTS, -np.inf)
    cmin = np.full(N_JOINTS, np.inf); cmax = np.full(N_JOINTS, -np.inf)
    q0: List[np.ndarray] = []
    n_frames = 0
    used: List[str] = []
    for td in take_dirs:
        p = os.path.join(td, "vectors.h5")
        if not os.path.isfile(p):
            continue
        with h5py.File(p, "r") as f:
            if "ur_joint_states" not in f:
                continue
            g = f["ur_joint_states"]
            q = np.stack([g[f"q{i + 1}"][:] for i in range(N_JOINTS)], 1)
            q = q[np.all(np.isfinite(q), axis=1)]
            if not len(q):
                continue
            qmin = np.minimum(qmin, q.min(0)); qmax = np.maximum(qmax, q.max(0))
            q0.append(q[0]); n_frames += len(q)
            if "command" in f:
                c = np.stack([f["command"][f"cmd{i + 1}"][:] for i in range(N_JOINTS)], 1)
                c = c[np.all(np.isfinite(c), axis=1)]
                if len(c):
                    cmin = np.minimum(cmin, c.min(0)); cmax = np.maximum(cmax, c.max(0))
        used.append(os.path.basename(td.rstrip("/")))
    if not used:
        raise FileNotFoundError("no take with ur_joint_states found")
    q0a = np.stack(q0, 0)
    return {"takes": used, "n_frames": int(n_frames), "joint_raw_min": qmin, "joint_raw_max": qmax,
            "command_min": cmin, "command_max": cmax, "start_pose_mean": q0a.mean(0), "start_pose_std": q0a.std(0),
            "start_pose_max_dev": np.abs(q0a - q0a.mean(0)).max(0)}


def _git() -> str:
    try:
        return subprocess.run(["git", "rev-parse", "--short", "HEAD"], cwd=_ROOT, capture_output=True, text=True,
                              timeout=3).stdout.strip() or "unknown"
    except Exception:  # noqa: BLE001
        return "unknown"


def _fmt(v) -> str:
    return "[" + ", ".join(f"{float(x):.4f}" for x in v) + "]"


def yaml_block(scan: Dict[str, Any], lo: np.ndarray, hi: np.ndarray, factor: float, source: str) -> str:
    rmin, rmax = quantise_outward(scan["joint_raw_min"], scan["joint_raw_max"])
    out_cmd = np.any(scan["command_min"] < lo) or np.any(scan["command_max"] > hi)
    lines = [
        f"  # --- joint envelope derived by sim_collect/eval/derive_limits.py ({_dt.datetime.now().isoformat(timespec='seconds')}, git {_git()}) ---",
        f"  # source: {source} ({len(scan['takes'])} takes, {scan['n_frames']} ur_joint_states rows); rule = the real",
        f"  # carrot_eef_limits.json rule: {factor:.1f}x symmetric about the centre of the OBSERVED joints, quantised outward 0.0001.",
        f"  # joint_raw_min: {_fmt(rmin)}",
        f"  # joint_raw_max: {_fmt(rmax)}",
        f"  # recorded `command` min/max (excluded from the envelope, as in the real rule; {'LEAVES' if out_cmd else 'inside'} it):",
        f"  #   {_fmt(scan['command_min'])} / {_fmt(scan['command_max'])}",
        f"  joint_limits_lo: {_fmt(lo)}",
        f"  joint_limits_hi: {_fmt(hi)}",
        f"  # sim start pose (ur_joint_states row 0, mean / std / max_dev over takes) — reference only:",
        f"  #   {_fmt(scan['start_pose_mean'])} / {_fmt(scan['start_pose_std'])} / {_fmt(scan['start_pose_max_dev'])}",
    ]
    return "\n".join(lines)


def main(argv: Optional[List[str]] = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("takes", nargs="+", help="take directories or directories of take_* folders")
    ap.add_argument("--factor", type=float, default=1.2)
    ap.add_argument("--json", default=None, help="also write the numbers as JSON")
    args = ap.parse_args(argv)
    from sim_collect.eval.run_eval import list_takes
    dirs = list_takes(",".join(args.takes))
    scan = scan_takes(dirs)
    lo, hi = expand(scan["joint_raw_min"], scan["joint_raw_max"], args.factor)
    print(yaml_block(scan, lo, hi, args.factor, ",".join(args.takes)))
    if args.json:
        with open(args.json, "w") as f:
            json.dump({k: (v.tolist() if isinstance(v, np.ndarray) else v) for k, v in scan.items()}
                      | {"factor": args.factor, "joint_limits_lo": lo.tolist(), "joint_limits_hi": hi.tolist()}, f, indent=2)
    return 0


if __name__ == "__main__":
    sys.exit(main())
